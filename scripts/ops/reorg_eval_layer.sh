#!/usr/bin/env bash
set -euo pipefail

# Conservative scaffold for the [6] evaluation-layer reorg.
#
# Default mode is dry-run. With DRY_RUN=0 this script creates the target
# directory/living-doc skeleton and a manifest, but it does not archive or move
# historical files unless MOVE_ARCHIVE=1 is explicitly set.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DRY_RUN="${DRY_RUN:-1}"
MOVE_ARCHIVE="${MOVE_ARCHIVE:-0}"

DOC_DIR="$ROOT/docs/analysis"
SCRIPT_DIR="$ROOT/scripts/analysis"
MANIFEST="$DOC_DIR/_reorg_eval_layer_manifest.md"

docs=(
  model_vs_market
  market_structure_edge
  execution_quality
  entry_timing
  side_alpha
  city_selection
  sizing_entry_band
  blender_shadow
  live_performance
  account_reconcile
  data_integrity
)

script_dirs=(
  model_vs_market
  market_structure
  execution
  entry_timing
  side_alpha
  city_selection
  sizing
  blender
  live_performance
  account
  data_integrity
)

run() {
  if [[ "$DRY_RUN" == "1" ]]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

write_file() {
  local path="$1"
  local title="$2"
  if [[ "$DRY_RUN" == "1" ]]; then
    echo "[dry-run] write $path"
    return
  fi
  if [[ -e "$path" ]]; then
    echo "skip existing $path"
    return
  fi
  cat >"$path" <<EOF
# ${title}

> Living doc scaffold generated by \`scripts/ops/reorg_eval_layer.sh\`.
> Fill this from archived snapshots only after validating data freshness and source-of-truth status.

## Current Conclusion

- Status: \`inconclusive\`
- Last updated: TODO
- Source module: TODO

## Evidence Map

| Evidence | Window | Data source | Status |
|---|---|---|---|
| TODO | TODO | TODO | TODO |

## Open Gaps

- TODO
EOF
}

echo "ROOT=$ROOT"
echo "DRY_RUN=$DRY_RUN MOVE_ARCHIVE=$MOVE_ARCHIVE"

for d in "${script_dirs[@]}"; do
  run mkdir -p "$SCRIPT_DIR/$d"
done

run mkdir -p "$DOC_DIR/_archive"

for doc in "${docs[@]}"; do
  title="$(tr '_' ' ' <<<"$doc")"
  title="$(python3 - <<PY
text = "$title"
print(" ".join(word.capitalize() for word in text.split()))
PY
)"
  write_file "$DOC_DIR/$doc.md" "$title"
done

if [[ "$DRY_RUN" == "1" ]]; then
  echo "[dry-run] write $MANIFEST"
else
  cat >"$MANIFEST" <<EOF
# Evaluation Layer Reorg Manifest

Generated by \`scripts/ops/reorg_eval_layer.sh\`.

This script created living-doc scaffolds and analysis subdirectories only.
Historical archive moves require \`MOVE_ARCHIVE=1\` and should be reviewed in git before commit.

## Living Docs

$(printf -- '- `%s.md`\n' "${docs[@]}")

## Script Directories

$(printf -- '- `%s/`\n' "${script_dirs[@]}")
EOF
fi

if [[ "$MOVE_ARCHIVE" != "1" ]]; then
  echo "Archive moves skipped. Set MOVE_ARCHIVE=1 after reviewing a concrete move list."
  exit 0
fi

echo "MOVE_ARCHIVE=1 was set, but no automatic archive move list is embedded yet."
echo "Add explicit git mv rules after reviewing docs/WEATHER_ARCHITECTURE_SPINE.md."
