#!/usr/bin/env python3
"""Train the PIT-compatible Amsterdam remaining-heat V8 weather model.

Model selection is confined to target dates ending on 2025-12-31.  August
2026 is deliberately absent from this program: it is scored by the separate
frozen-forward replay after the artifact and policy manifest are written.
"""

from __future__ import annotations

